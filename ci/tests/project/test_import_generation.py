"""Common facade maintenance contracts; no Lean, Git or dependency operations."""
from contextlib import redirect_stderr, redirect_stdout
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from lean_ci.project.configuration import load_config
from lean_ci.checks import guards
from lean_ci.project import imports
from lean_ci.cli import main
from lean_ci.project.source import lean_imports

MARKER = '-- Generated by scripts/generate_imports.py; do not edit by hand.'
HEADER = '/-\nCopyright (c) 2026 Contributors.\nAuthors: Contributors\n-/\n\n'


class ImportGenerationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.write('lean-toolchain', 'leanprover/lean4:v4.34.1\n')
        self.write('lakefile.toml', 'name="Fixture"\n[[lean_lib]]\nname="Lib"\n')
        self.write('Lib.lean', 'module\npublic import Lib.Topic\n')
        self.write('Lib/Topic.lean', HEADER + MARKER + '\nmodule\n')
        self.write('Lib/Topic/First.lean', '/-\nCopyright (c) 2026 A.\nAuthors: Alice\n-/\nmodule\n')
        self.render = {'header': HEADER, 'description': '# {family}\n\nThe `{module}` family.',
                       'modern': True, 'authors': True, 'long_file_limit': 1500}
        self.policy(top_level=False)

    def write(self, path, text):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)

    def policy(self, *, top_level=False, generated=()):
        self.write('.github/lean-ci.toml', 'schema=1\n[roles]\nproduction=["Lib"]\n'
                   '[policy]\nstyle=[".github/style.json"]\n')
        self.write('.github/style.json', json.dumps({'schema': 1, 'kind': 'source',
            'generated': list(generated), 'discover_generated': [{'root': 'Lib',
            'exclude': ['Lib'], 'marker': MARKER, 'top_level': top_level,
            'excluded_families': ['Examples'], 'render': self.render}]}))

    def outputs(self):
        return guards.generated_files(self.root, load_config(self.root))

    def maintain(self, write=False):
        try:
            result = imports.maintain(self.root, write=write)
            return 0 if write or not result['changed'] else 1
        except ValueError:
            return 1

    def snapshot(self):
        return {p.relative_to(self.root).as_posix(): p.read_bytes() for p in self.root.rglob('*.lean')}

    def test_opt_in_topics_preserve_curated_roots_and_manual_ownership(self):
        self.write('Lib/Manual.lean', 'module\npublic import Lib.Manual.Child\n')
        self.write('Lib/Manual/Child.lean', 'module\n')
        self.write('Lib/Implicit/Child.lean', 'module\n')
        self.write('Lib/Quoted.lean', '/-!\n' + MARKER + '\n-/\nmodule\n')
        self.write('Lib/Quoted/Child.lean', 'module\n')
        before = self.snapshot()
        self.assertEqual(set(self.outputs()), {'Lib/Topic.lean'})
        self.assertEqual(self.maintain(write=True), 0)
        for name in ('Lib.lean', 'Lib/Manual.lean', 'Lib/Quoted.lean'):
            self.assertEqual((self.root / name).read_bytes(), before[name])
        self.assertFalse((self.root / 'Lib/Implicit.lean').exists())

    def test_nested_topics_track_sorted_additions_deletions_and_credits(self):
        self.write('Lib/Topic/Nested.lean', MARKER + '\nmodule\n')
        self.write('Lib/Topic/Nested/Zebra.lean', '/-\nCopyright (c) 2026 B.\nAuthors: Bob\n-/\nmodule\n')
        self.assertEqual(self.maintain(write=True), 0)
        output = self.outputs()
        self.assertIn('Authors: Alice, Bob', output['Lib/Topic.lean'])
        self.assertEqual(lean_imports(output['Lib/Topic/Nested.lean']), ['Lib.Topic.Nested.Zebra'])
        (self.root / 'Lib/Topic/Nested/Zebra.lean').unlink()
        self.write('Lib/Topic/Nested/Alpha.lean', 'module\n')
        self.assertEqual(self.maintain(), 1)
        self.assertEqual(self.maintain(write=True), 0)
        self.assertEqual(self.maintain(), 0)

    def test_top_level_discovery_creates_only_occupied_nonexcluded_facades(self):
        self.policy(top_level=True)
        self.write('Lib/New/Leaf.lean', 'module\n')
        self.write('Lib/Examples/Example.lean', 'module\n')
        (self.root / 'Lib/Empty').mkdir()
        self.assertEqual(self.maintain(write=True), 0)
        self.assertEqual(lean_imports((self.root / 'Lib/New.lean').read_text()), ['Lib.New.Leaf'])
        self.assertFalse((self.root / 'Lib/Examples.lean').exists())
        self.assertFalse((self.root / 'Lib/Empty.lean').exists())

    def test_marked_implementation_and_unoccupied_topic_fail_without_writes(self):
        for source in (MARKER + '\nmodule\ndef value := 1\n', MARKER + '\nmodule\n'):
            with self.subTest(source=source):
                self.write('Lib/Invalid.lean', source)
                before = self.snapshot()
                self.assertEqual(self.maintain(write=True), 1)
                self.assertEqual(self.snapshot(), before)
        (self.root / 'Lib/Invalid.lean').unlink()

    def test_modern_topic_rejects_legacy_child_without_writes(self):
        self.write('Lib/Topic/Legacy.lean', 'import Lib.Topic.First\n')
        before = self.snapshot()
        self.assertEqual(self.maintain(write=True), 1)
        self.assertEqual(self.snapshot(), before)

    def test_new_edges_between_facades_are_checked_before_any_write(self):
        self.write('Lib/Other.lean', MARKER + '\nmodule\n')
        self.write('Lib/Other/Leaf.lean', 'module\npublic import Lib.Topic\n')
        self.write('Lib/Topic/First.lean', 'module\npublic import Lib.Other\n')
        before = self.snapshot()
        self.assertEqual(self.maintain(write=True), 1)
        self.assertEqual(self.snapshot(), before)

    def test_write_rechecks_source_ownership_before_overwriting_any_product(self):
        original = imports._products
        manual = 'module\npublic import Lib.Topic.First\n'
        def takeover(*args, **kwargs):
            result = original(*args, **kwargs)
            self.write('Lib/Topic.lean', manual)
            return result
        with patch.object(imports, '_products', side_effect=takeover):
            self.assertEqual(self.maintain(write=True), 1)
        self.assertEqual((self.root / 'Lib/Topic.lean').read_text(), manual)

    def test_missing_explicit_exhaustive_root_can_be_created_without_takeover(self):
        (self.root / 'Lib.lean').unlink()
        self.policy(generated=[{'module': 'Lib', 'mode': 'exhaustive', 'marker': MARKER,
                                'render': self.render}])
        self.assertEqual(self.maintain(write=True), 0)
        self.assertEqual(lean_imports((self.root / 'Lib.lean').read_text()),
                         ['Lib.Topic', 'Lib.Topic.First'])

    def test_rendering_preserves_wrapping_and_finite_generated_long_file_bound(self):
        self.render['long_file_limit'] = 6
        self.policy()
        name = 'Lib.Topic.' + 'Long' * 21
        self.write(name.replace('.', '/') + '.lean', 'module\n')
        self.assertEqual(self.maintain(write=True), 0)
        source = (self.root / 'Lib/Topic.lean').read_text()
        self.assertIn('public import\n  ' + name, source)
        self.assertIn('set_option linter.style.longFile 200', source)

    def test_restored_policy_or_source_and_changed_head_block_all_writes(self):
        for changed in ('Lib/Topic/First.lean', '.github/style.json', 'HEAD'):
            with self.subTest(changed=changed):
                original = imports._products
                head = ['original']
                before = self.snapshot()
                def mutate(*args, **kwargs):
                    result = original(*args, **kwargs)
                    if changed == 'HEAD':
                        head[0] = 'changed'
                    else:
                        path = self.root / changed
                        raw = path.read_bytes()
                        path.write_bytes(raw + b'\n')
                        path.write_bytes(raw)
                    return result
                with patch.object(imports, '_products', side_effect=mutate), \
                        patch.object(imports, '_head', side_effect=lambda _: head[0]):
                    self.assertEqual(self.maintain(write=True), 1)
                self.assertEqual(self.snapshot(), before)

    def test_test_roots_use_declared_positive_formal_and_negative_roles(self):
        self.write('lakefile.toml', (self.root / 'lakefile.toml').read_text() +
                   '[[lean_lib]]\nname="Tests"\n')
        self.write('Tests.lean', MARKER + '\n')
        self.write('Tests/Modern.lean', 'module\n')
        self.write('Tests/Legacy.lean', 'import Lib.Topic.First\n')
        self.write('Tests/Audit.lean', 'import Lib\n')
        self.write('Tests/Negative.lean', 'axiom bad : False\n')
        for include_formal in (False, True):
            self.policy(generated=[{'module': 'Tests', 'mode': 'exhaustive', 'marker': MARKER,
                'roles': ['tests', 'formal_only'] if include_formal else ['tests'],
                'render': {**self.render, 'modern': 'all'}}])
            path = self.root / '.github/lean-ci.toml'
            path.write_text(path.read_text().replace('[roles]',
                'formal_only=["Tests/Audit.lean"]\nexpected_failure=["Tests/Negative.lean"]\n[roles]')
                .replace('production=["Lib"]', 'production=["Lib"]\ntests=["Tests"]'))
            self.assertEqual(self.maintain(write=True), 0)
            imports_found = lean_imports((self.root / 'Tests.lean').read_text())
            self.assertEqual(imports_found, ['Tests.Audit', 'Tests.Legacy', 'Tests.Modern']
                             if include_formal else ['Tests.Legacy', 'Tests.Modern'])
            self.assertNotIn('module\n', (self.root / 'Tests.lean').read_text())

    def test_shared_cli_checks_by_default_and_forwards_explicit_writes(self):
        arguments = ['imports', '--root', str(self.root)]
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            self.assertEqual(main(arguments), 1)
            self.assertEqual(main([*arguments, '--write']), 0)
            self.assertEqual(main([*arguments, '--check']), 0)


if __name__ == '__main__':
    unittest.main()
