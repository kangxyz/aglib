LIBRARIES = {data['package']: name for name, data in PROFILES.items()}

def configuration(root):
    path = Path(root) / 'lakefile.toml'
    return tomllib.loads(path.read_text()) if path.is_file() else {}

def family(root):
    return LIBRARIES.get(configuration(root).get('name'))

def profile(root):
    selected = family(root)
    if selected is None and not (Path(root) / 'lakefile.toml').exists():
        matches = [name for name, data in PROFILES.items()
                   if (Path(root) / data['production']).is_dir()
                   or (Path(root) / (data['production'] + '.lean')).is_file()]
        selected = matches[0] if len(matches) == 1 else None
    if selected is None:
        raise ValueError('Select a package with a supported Lake name')
    return PROFILES[selected]

def local_roots(root):
    selected = family(root)
    names = ((PROFILES[selected]['production'],) if selected else
             tuple(configuration(root).get('defaultTargets', ())))
    return tuple(dict.fromkeys(name for base in names for name in (base, base + 'Test')))

def resource_config(selected):
    from .resources import ResourceConfig
    data = PROFILES[selected]
    aliases = data.get('resource_aliases', False)
    return ResourceConfig(prefix=selected.upper(),
        profile_keys=('R5_LEAN_REMOTE_PROFILE', *data.get('profile_aliases', ())),
        memory_keys=('AGLIB_LEAN_MEMORY_MB',) if aliases else (),
        rss_keys=('AGLIB_RSS_LIMIT_MB',) if aliases else (),
        build_thread_keys=('AGLIB_BUILD_THREADS',) if aliases else ())

def runtime_environment(selected):
    environment = dict(os.environ)
    if PROFILES[selected].get('normalize_aliases'):
        for suffix in ('BUILD_THREADS', 'LEAN_MEMORY_MB', 'RSS_LIMIT_MB'):
            name = selected.upper() + '_' + suffix
            if name in environment:
                environment['AGLIB_' + suffix] = environment[name]
    return environment

def options(root):
    from .local import SourceCheck
    selected = family(root)
    if selected is None:
        return {'production': tuple(configuration(root).get('defaultTargets', ()))}
    package = Path(__file__).resolve().parent
    inputs = tuple(package / name for name in ('library.py', 'policy.py', 'imports.py',
                                               'source.py', 'cli.py', '__main__.py'))
    return dict(production=(PROFILES[selected]['production'],), check_targets=(),
        resource_config=resource_config(selected), environment=runtime_environment(selected),
        source_checks=(SourceCheck(
            (sys.executable, str(package / '__main__.py'), 'source', '--root', str(root)),
            inputs, (Path(root) / 'examples/downstream',)),))
