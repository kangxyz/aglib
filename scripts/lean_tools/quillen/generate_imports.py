#!/usr/bin/env python3
"""Generate thematic facades and the downstream root; native tools own library/Test discovery."""
import argparse
from pathlib import Path
import sys

from .library_sources import (downstream_sources, module_name, source_modules, test_modules,
                             uses_module_system)

ROOT = Path.cwd()
# Example clients are enrolled at the root without a generated family facade.
# Existing facades opt into generator ownership only through this exact marker.
EXCLUDED_FAMILIES = {'Examples'}
GENERATED_MARKER = '-- Generated by scripts/generate_imports.py; do not edit by hand.\n'
COPYRIGHT_HEADER = '''/-
Copyright (c) 2026 Quillen K-theory contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Quillen K-theory contributors
-/

'''


def generator_owned(source: str) -> bool:
    """Accept the exact leading marker, optionally after a copyright header.

    A marker quoted in documentation or mentioned after manual source commands
    never transfers ownership to the generator.
    """
    if source.startswith('/-\nCopyright (c) '):
        end = source.find('-/')
        if end < 0:
            return False
        source = source[end + 2:].lstrip('\r\n')
    return source.startswith(GENERATED_MARKER)


def source_authors(source: str) -> set[str]:
    """Read comma-separated credits only from the initial copyright header."""
    if not source.startswith('/-\nCopyright (c) '):
        return set()
    end = source.find('-/')
    if end < 0:
        return set()
    return {name.strip() for line in source[:end].splitlines()
            if line.startswith('Authors:')
            for name in line.removeprefix('Authors:').split(',') if name.strip()}


def family_facades(root: Path) -> set[Path]:
    """Create top-level surfaces; enroll existing nested opt-in surfaces only."""
    occupied_families = {path.parts[1] for path in source_modules(root)
                         if len(path.parts) > 2}
    top_level = {Path('Quillen') / (path.name + '.lean')
            for path in (root / 'Quillen').iterdir()
            if path.is_dir() and path.name in occupied_families
            and path.name not in EXCLUDED_FAMILIES
            and not path.name.startswith('.')}
    nested = {path.relative_to(root) for path in (root / 'Quillen').rglob('*.lean')
              if len(path.relative_to(root).parts) > 2
              and path.with_suffix('').is_dir() and generator_owned(path.read_text())}
    return top_level | nested


def render_imports(modules: list[str], description: str, modern: bool = False,
                   authors: set[str] | None = None) -> str:
    prefix = 'public import ' if modern else 'import '
    # Complete import lines are exempt from mathlib's long-line lint, but
    # continued module names are not. Keep names that cannot fit intact.
    imports = [prefix + name if len(prefix + name) <= 100 or len(name) + 2 > 100
               else prefix.rstrip() + '\n  ' + name for name in sorted(modules)]
    header = COPYRIGHT_HEADER
    if authors:
        header = header.replace('Authors: Quillen K-theory contributors',
                                'Authors: ' + ', '.join(sorted(authors)))
    source = (header + GENERATED_MARKER
            + ('module\n\n' if modern else '')
            + '\n'.join(imports)
            + '\n\n/-!\n' + description + '\n-/\n')
    # Import surfaces grow with the discovered graph, independently of proof size.
    source += ('\n-- The import-only facade follows the discovered source graph.\n'
               'set_option linter.style.longFile 0\n')
    return source


def generated_files(root: Path, modern_library: bool | None = None) -> dict[Path, str]:
    """Existing implementations are discovered; only these facades are managed."""
    modules = source_modules(root) - {Path('Quillen.lean')}
    # Snapshot hand-owned credits before adding generated surfaces. Existing
    # generated headers are never inputs, even when their credits are stale.
    authors = {path: source_authors(source) for path in modules
               if not generator_owned(source := (root / path).read_text())}
    if modern_library is None:
        library_root = root / 'Quillen.lean'
        modern_library = library_root.exists() and uses_module_system(library_root.read_text())
    outputs = {}
    for facade in sorted(family_facades(root)):
        family = facade.stem
        directory = facade.with_suffix('')
        if (root / facade).exists() and not generator_owned((root / facade).read_text()):
            # The existing source is manually owned. It remains enrolled at the
            # exhaustive root, but generation must not take over its contents.
            continue
        outputs[facade] = render_imports(
            [module_name(path) for path in modules if directory in path.parents],
            f'# {family}\n\nAll modules in the `{module_name(facade)}` family.\n'
            'Use an individual module import for a smaller dependency closure.', modern_library,
            {name for path, names in authors.items() if directory in path.parents
             for name in names})
        modules.add(facade)
    if modern_library:
        legacy = sorted(path for path in modules if path not in outputs
                        and not uses_module_system((root / path).read_text()))
        if legacy:
            raise ValueError('Modern library facades cannot import legacy sources: '
                             + ', '.join(map(str, legacy)))
    client_root = Path('examples/downstream/Consumer.lean')
    client_directory = client_root.with_suffix('')
    clients = {path for path in downstream_sources(root)
               if client_directory in path.parents}
    if clients or (root / client_root).exists():
        modern_client = (not (root / client_root).exists()
                         or uses_module_system((root / client_root).read_text()))
        if modern_client:
            legacy = sorted(path for path in clients
                            if not uses_module_system((root / path).read_text()))
            if legacy:
                raise ValueError('Modern Consumer facade cannot import legacy sources: '
                                 + ', '.join(map(str, legacy)))
        outputs[client_root] = render_imports(
            [module_name(path.relative_to('examples/downstream')) for path in clients],
            'Independently compiled downstream consumers of the public library.', modern_client,
            {name for path in clients
             if not generator_owned(source := (root / path).read_text())
             for name in source_authors(source)})
        if modern_client:
            outputs[client_root] += '\n@[expose] public section\n'
    return outputs


def stale_files(root: Path, modern_library: bool | None = None) -> list[Path]:
    return [path for path, expected in generated_files(root, modern_library).items()
            if not (root / path).is_file() or (root / path).read_text() != expected]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated imports are stale')
    parser.add_argument('--root', type=Path, default=ROOT, help='project root (defaults to this checkout)')
    parser.add_argument('--modern-library', action='store_true', default=None,
                        help='migrate library facades after every implementation uses module headers')
    args = parser.parse_args(argv)
    try:
        outputs = generated_files(args.root, args.modern_library)
    except (OSError, ValueError) as error:
        print(f'Import generation failed: {error}', file=sys.stderr)
        return 1
    if args.check:
        stale = stale_files(args.root, args.modern_library)
        if stale:
            print('Stale generated imports: ' + ', '.join(map(str, stale))
                  + '\nRun lean-tools quillen imports', file=sys.stderr)
            return 1
    else:
        # Recheck ownership before any writes: another editor may have created
        # or taken over a family facade after discovery.
        exhaustive_roots = {Path('examples/downstream/Consumer.lean')}
        conflicts = [path for path in outputs if path not in exhaustive_roots
                     and (args.root / path).exists()
                     and not generator_owned((args.root / path).read_text())]
        if conflicts:
            print('Refusing to overwrite manually owned facades: '
                  + ', '.join(map(str, conflicts)), file=sys.stderr)
            return 1
        for path, content in outputs.items():
            (args.root / path).write_text(content)
    print(f'Generated imports {"checked" if args.check else "written"}: '
          f'{len(outputs)} files; {len(source_modules(args.root))} library modules; '
          f'{len(test_modules(args.root))} trust-test modules.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
