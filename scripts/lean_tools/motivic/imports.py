#!/usr/bin/env python3
# Authors: kangxyz
"""Refresh existing opt-in topic facades; native tools own production/test discovery.

Ownership-marker convention adapted from kangxyz/aglib scripts/generate_imports.py,
revision 3c571e67a3180565bfb4e6e634fb17d0e5b0b9e1, Apache-2.0. Copyright (c) 2026 Algebraic geometry contributors;
Authors: kangxyz. This generator deliberately has no exhaustive-root mode.
"""
import argparse
from pathlib import Path
import sys

from .sources import (ROOTS, is_import_surface, lean_imports, source_modules,
                             uses_module_system)

ROOT = Path.cwd()
GENERATED_MARKER = '-- Generated by scripts/generate_imports.py; do not edit by hand.\n'


def ownership_prefix(source: str) -> str | None:
    """Return the retained copyright prefix only for an exact leading marker."""
    prefix = ''
    if source.startswith('/-\nCopyright (c) '):
        end = source.find('-/')
        if end < 0:
            return None
        end += 2
        while end < len(source) and source[end] in '\r\n':
            end += 1
        prefix, source = source[:end], source[end:]
    return prefix if source.startswith(GENERATED_MARKER) else None


def generator_owned(source: str) -> bool:
    return ownership_prefix(source) is not None


def generated_files(root: Path) -> dict[Path, str]:
    """Plan all enrolled updates and reject invalid ownership or cycles first."""
    sources = source_modules(root)
    texts = {name: path.read_text() for name, path in sources.items()}
    outputs = {}
    for name, path in sorted(sources.items()):
        source = texts[name]
        if name in ROOTS or not generator_owned(source):
            continue
        relative = path.relative_to(root)
        if not is_import_surface(source):
            raise ValueError(f'{relative}: marked facade contains implementation commands; '
                             'refusing to overwrite')
        directory = path.with_suffix('')
        children = sorted(child for child, child_path in sources.items()
                          if directory in child_path.parents)
        if not directory.is_dir() or not children:
            raise ValueError(f'{relative}: generated facade requires an occupied same-named directory')
        legacy = [child for child in children if not uses_module_system(texts[child])
                  and not generator_owned(texts[child])]
        if legacy:
            raise ValueError(f'{relative}: modern facade has legacy child sources: ' + ', '.join(legacy))
        outputs[relative] = (ownership_prefix(source) + GENERATED_MARKER + 'module\n\n'
                             + ''.join(f'public import {child}\n' for child in children)
                             + '\n/-!\nAll modules in this family.\n\n'
                             'Import individual leaves for a smaller dependency closure.\n-/\n'
                             '\n-- Generated import entries grow with the source graph.\n'
                             'set_option linter.style.longFile 0\n')
    # Only proposed facade edges need a new cycle check; the repository checker
    # already diagnoses the actual graph. Include all proposed updates together.
    graph = {name: set(lean_imports(outputs.get(path.relative_to(root), texts[name])))
             & sources.keys() for name, path in sources.items()}
    for name, path in sorted(sources.items()):
        if path.relative_to(root) not in outputs:
            continue
        pending = [(child, [name, child]) for child in sorted(graph[name], reverse=True)]
        seen = set()
        while pending:
            child, route = pending.pop()
            if child == name:
                raise ValueError('Generated facade import cycle: ' + ' -> '.join(route))
            if child in seen:
                continue
            seen.add(child)
            pending.extend((target, route + [target]) for target in sorted(graph[child], reverse=True))
    return outputs


def stale_files(root: Path) -> list[Path]:
    return [path for path, expected in generated_files(root).items()
            if (root / path).read_text() != expected]


def check_generated(root: Path) -> list[str]:
    """Return enrollment errors for the structural checker without writing."""
    try:
        stale = stale_files(root)
    except ValueError as error:
        return [str(error)]
    return (['Stale generated facades: ' + ', '.join(map(str, stale))
             + '; run python3 scripts/generate_imports.py'] if stale else [])


def write_generated(root: Path, outputs: dict[Path, str]) -> None:
    # Replan before the first write to catch ownership, family or graph edits
    # since discovery. This does not claim synchronization with concurrent writers.
    if generated_files(root) != outputs:
        raise ValueError('Facade inputs changed during generation; retry after source edits finish')
    for path, content in outputs.items():
        if (root / path).read_text() != content:
            (root / path).write_text(content)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true', help='report stale enrolled facades without writing')
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve()
        outputs = generated_files(root)
        if args.check:
            stale = [path for path, content in outputs.items() if (root / path).read_text() != content]
            if stale:
                raise ValueError('Stale generated facades: ' + ', '.join(map(str, stale))
                                 + '; run python3 scripts/generate_imports.py')
        else:
            write_generated(root, outputs)
    except (OSError, UnicodeError, ValueError) as error:
        print(f'Import generation failed: {error}', file=sys.stderr)
        return 1
    print(f'Generated topic facades {"checked" if args.check else "written"}: {len(outputs)}; '
          'Native mk_all owns Motivic.lean; MotivicTest leaves are discovered by Lake globs.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
