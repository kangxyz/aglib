GENERATED_MARKER = '-- Generated by scripts/generate_imports.py; do not edit by hand.\n'


def ownership_prefix(source, data=None):
    prefix = ''
    if source.startswith('/-\nCopyright (c) '):
        end = source.find('-/')
        if end < 0:
            return None
        end += 2
        while end < len(source) and source[end] in '\r\n':
            end += 1
        prefix, source = source[:end], source[end:]
    markers = (data['generated_markers'] if data else
               tuple(marker for row in PROFILES.values() for marker in row['generated_markers']))
    return prefix if source.startswith(markers) else None


def generator_owned(source, data=None):
    return ownership_prefix(source, data) is not None


def source_authors(source):
    if not source.startswith('/-\nCopyright (c) '):
        return set()
    end = source.find('-/')
    if end < 0:
        return set()
    return {name.strip() for line in source[:end].splitlines() if line.startswith('Authors:')
            for name in line.removeprefix('Authors:').split(',') if name.strip()}


def render_imports(modules, description, modern=False, authors=None, *, data, header=None):
    prefix = 'public import ' if modern else 'import '
    width = data.get('wrap_imports')
    lines = [prefix.rstrip() + '\n  ' + name
             if width and len(prefix + name) > width and len(name) + 2 <= width
             else prefix + name for name in sorted(modules)]
    if header is None:
        header = data['copyright_header']
        if authors:
            header = re.sub(r'^Authors:.*$', 'Authors: ' + ', '.join(sorted(authors)), header, flags=re.M)
    return (header + data['generated_marker'] + ('module\n\n' if modern else '')
            + '\n'.join(lines) + '\n\n/-!\n' + description + '\n-/\n' + data['footer'])


def generated_files(root, modern_library=None, *, selected=None, sources=None, texts=None):
    root = Path(root)
    data = profile(root)
    production = data['production']
    roots = {production, production + 'Test'}
    sources = dict(source_modules(root) if sources is None else sources)
    texts = dict({name: path.read_text() for name, path in sources.items()} if texts is None else texts)
    mode = data['generation']
    candidates = set()
    if selected is not None:
        if MODULE.fullmatch(selected) is None or not selected.startswith(production + '.'):
            raise ValueError('Select a local topic; native mk_all owns the production root')
        path = root / module_path(selected)
        if not path.resolve().is_relative_to((root / production).resolve()) or path.is_symlink() or path.with_suffix('').is_symlink():
            raise ValueError('The topic entry must stay in this package')
        candidates.add(selected)
    elif mode != 'explicit':
        candidates = {name for name in sources if name not in roots and generator_owned(texts[name], data)}
        if mode == 'top-level':
            candidates = {name for name in candidates if len(module_path(name).parts) > 2
                          and sources[name].with_suffix('').is_dir()}
            occupied = {module_path(name).parts[1] for name in sources
                        if name.startswith(production + '.') and len(module_path(name).parts) > 2}
            candidates.update(production + '.' + path.name for path in (root / production).iterdir()
                              if path.is_dir() and path.name in occupied
                              and path.name not in data.get('excluded_families', ())
                              and not path.name.startswith('.'))
    modern = data['modern_generation']
    if modern == 'root':
        facade = root / (production + '.lean')
        modern = bool(facade.is_file() and uses_module_system(facade.read_text()))
    if modern_library is not None:
        modern = modern_library
    outputs = {}
    all_paths = {**sources, **{name: root / module_path(name) for name in candidates}}
    authors = {name: source_authors(text) for name, text in texts.items()
               if not generator_owned(text, data)}
    for name in sorted(candidates, key=lambda item: module_path(item)):
        path = all_paths[name]
        relative = path.relative_to(root)
        original = texts.get(name)
        if original is not None and not generator_owned(original, data):
            if selected is not None:
                raise ValueError('Preserve the manually owned or non-import-only topic entry')
            continue
        if original is not None and not is_import_surface(original):
            raise ValueError(f'{relative}: marked facade contains implementation commands; refusing to overwrite')
        directory = path.with_suffix('')
        children = sorted(child for child, child_path in all_paths.items() if directory in child_path.parents)
        if not directory.is_dir() or not children:
            raise ValueError(f'{relative}: generated facade requires an occupied same-named directory')
        if selected is not None and any(all_paths[child].is_symlink() for child in children):
            raise ValueError('Topic source files must belong to this package')
        if data.get('generation_modern_children'):
            legacy = [child for child in children if child in texts
                      and not uses_module_system(texts[child]) and not generator_owned(texts[child], data)]
            if legacy:
                raise ValueError(f'{relative}: modern facade has legacy child sources: ' + ', '.join(legacy))
        header = ownership_prefix(original, data) if original is not None and data.get('preserve_header') else None
        if not header and data.get('copyright_header'):
            header = None
        credits = {author for child in children for author in authors.get(child, ())}
        outputs[relative] = render_imports(children,
            data['description'].format(module=name, family=path.stem), bool(modern),
            credits if data.get('collect_authors') else None, data=data, header=header)
    if modern and data.get('generation_modern_all'):
        legacy = sorted(path.relative_to(root) for name, path in sources.items()
                        if name.startswith(production + '.') and path.relative_to(root) not in outputs
                        and not uses_module_system(texts[name]))
        if legacy:
            raise ValueError('Modern library facades cannot import legacy sources: ' + ', '.join(map(str, legacy)))
    client_name = data.get('generated_client')
    if client_name and selected is None:
        clients = client_sources(root)
        children = {name: path for name, path in clients.items() if name.startswith(client_name + '.')}
        path = root / 'examples/downstream' / (client_name + '.lean')
        if children or path.exists():
            client_modern = not path.exists() or uses_module_system(path.read_text())
            client_texts = {name: child.read_text() for name, child in children.items()}
            if client_modern:
                legacy = [child for child, text in client_texts.items() if not uses_module_system(text)]
                if legacy:
                    raise ValueError('Modern ' + client_name + ' facade cannot import legacy sources: '
                                     + ', '.join(str(children[name].relative_to(root)) for name in legacy))
            credits = {author for text in client_texts.values() if not generator_owned(text, data)
                       for author in source_authors(text)}
            outputs[path.relative_to(root)] = render_imports(list(children), data['client_description'],
                client_modern, credits, data=data) + ('\n@[expose] public section\n' if client_modern else '')
    if data.get('generation_cycles'):
        graph = {name: set(lean_imports(outputs.get(path.relative_to(root), texts.get(name, ''))))
                 & all_paths.keys() for name, path in all_paths.items()}
        for relative in outputs:
            name = module_name(relative)
            pending = [(child, [name, child]) for child in sorted(graph.get(name, ()), reverse=True)]
            seen = set()
            while pending:
                child, route = pending.pop()
                if child == name:
                    raise ValueError('Generated facade import cycle: ' + ' -> '.join(route))
                if child in seen:
                    continue
                seen.add(child)
                pending.extend((target, route + [target]) for target in sorted(graph.get(child, ()), reverse=True))
    return outputs


def stale_files(root, modern_library=None, **kwargs):
    return [path for path, expected in generated_files(root, modern_library, **kwargs).items()
            if not (Path(root) / path).is_file() or (Path(root) / path).read_text() != expected]


def check_generated(root, **kwargs):
    try:
        stale = stale_files(root, **kwargs)
    except ValueError as error:
        return [str(error)]
    return (['Stale generated facades: missing enrollment or changed facade: '
             + ', '.join(map(str, stale)) + '; run lean-tools imports'] if stale else [])


def write_generated(root, outputs, modern_library=None, *, selected=None):
    if generated_files(root, modern_library, selected=selected) != outputs:
        raise ValueError('Facade inputs changed during generation; preserve concurrent edits')
    for path, content in outputs.items():
        target = Path(root) / path
        if not target.exists() or target.read_text() != content:
            target.write_text(content)


def generate_topic(root, name):
    outputs = generated_files(root, selected=name)
    write_generated(root, outputs, selected=name)
    return module_path(name)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path.cwd())
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--generate', metavar='MODULE')
    parser.add_argument('--modern-library', action='store_true', default=None)
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve()
        outputs = generated_files(root, args.modern_library, selected=args.generate)
        if args.check:
            stale = [path for path, text in outputs.items()
                     if not (root / path).is_file() or (root / path).read_text() != text]
            if stale:
                raise ValueError('Stale generated facades: ' + ', '.join(map(str, stale)))
        else:
            write_generated(root, outputs, args.modern_library, selected=args.generate)
    except (OSError, UnicodeError, ValueError) as error:
        print('Import generation failed: ' + str(error), file=sys.stderr)
        return 1
    print(f'Generated import facades {"checked" if args.check else "written"}: {len(outputs)}; native mk_all owns production roots.')
    return 0
