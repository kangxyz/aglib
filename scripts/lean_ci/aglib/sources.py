"""Repository inventory/routing adapter over the shared Lean lexical helpers."""
from pathlib import Path
from ..source import (IDENT, MODULE, IMPORT_START, KEYWORDS,
                            strip_comments_and_strings, lean_imports, import_header,
                            uses_module_system, is_import_surface, module_path, module_name)


def source_modules(root: Path) -> set[Path]:
    return {Path('Aglib.lean')} | {
        path.relative_to(root) for path in (root / 'Aglib').rglob('*.lean')}


def test_modules(root: Path) -> set[Path]:
    """Discover in-package tests without requiring a generated test umbrella."""
    modules = {path.relative_to(root) for path in (root / 'AglibTest').rglob('*.lean')}
    if (root / 'AglibTest.lean').is_file():
        modules.add(Path('AglibTest.lean'))
    return modules


def downstream_sources(root: Path) -> set[Path]:
    return {path.relative_to(root) for path in (root / 'examples/downstream').rglob('*.lean')
            if '.lake' not in path.relative_to(root).parts}


GENERATED_MARKER = '-- Generated by lean-ci aglib layout --generate; do not edit by hand.\n'
SCRIPT_GENERATED_MARKER = '-- Generated by scripts/check_library_layout.py --generate; do not edit by hand.\n'
LEGACY_GENERATED_MARKER = '-- Generated by scripts/generate_imports.py; do not edit by hand.\n'


def generate_topic(root: Path, name: str) -> Path:
    """Generate one explicitly selected topic entry, with a permanent size exemption."""
    root = root.resolve()
    if MODULE.fullmatch(name) is None or not name.startswith('Aglib.'):
        raise ValueError('Select an Aglib topic; native mk_all owns the production root')
    relative = module_path(name)
    path = root / relative
    directory = path.with_suffix('')
    if not path.resolve().is_relative_to(root / 'Aglib') or path.is_symlink():
        raise ValueError('The topic entry must stay in this package')
    if not directory.is_dir() or directory.is_symlink():
        raise ValueError('The selected topic needs an occupied source directory')
    original = path.read_text() if path.is_file() else None
    prefix = ''
    if original is not None:
        body = original
        if body.startswith('/-\nCopyright (c) '):
            end = body.find('-/')
            if end >= 0:
                end += 2
                prefix, body = body[:end] + '\n\n', body[end:].lstrip('\r\n')
        if not body.startswith((GENERATED_MARKER, SCRIPT_GENERATED_MARKER, LEGACY_GENERATED_MARKER)) or not is_import_surface(original):
            raise ValueError('Preserve the manually owned or non-import-only topic entry')
    children = sorted(directory.rglob('*.lean'))
    if not children:
        raise ValueError('The selected topic needs an occupied source directory')
    imports, authors = [], set()
    for child in children:
        if child.is_symlink():
            raise ValueError('Topic source files must belong to this package')
        source = child.read_text()
        if name in lean_imports(source):
            raise ValueError('A topic entry cannot import a consumer of that same entry')
        imports.append(module_name(child.relative_to(root)))
        if source.startswith('/-\nCopyright (c) '):
            header = source.split('-/', 1)[0]
            authors.update(author.strip() for line in header.splitlines()
                           if line.startswith('Authors:')
                           for author in line.removeprefix('Authors:').split(',') if author.strip())
    if not prefix:
        prefix = ('/-\nCopyright (c) 2026 Algebraic geometry contributors. All rights reserved.\n'
                  'Released under Apache 2.0 license as described in the file LICENSE.\n'
                  'Authors: ' + ', '.join(sorted(authors or {'Algebraic geometry contributors'})) + '\n-/\n\n')
    content = (prefix + GENERATED_MARKER + 'module\n\n'
               + ''.join('public import ' + item + '\n' for item in sorted(imports))
               + '\n/-!\nAll modules in the `' + name + '` family.\n'
               'Import individual leaves for a smaller dependency closure.\n-/\n'
               + '\n-- Generated import entries grow with the source graph.\n'
               'set_option linter.style.longFile 0\n')
    if (path.read_text() if path.is_file() else None) != original:
        raise ValueError('The topic entry changed during generation; preserve the concurrent edit')
    path.write_text(content)
    return relative
